#!/usr/bin/env python3
"""Convert Hacker's Keyboard layouts (klausw/hackerskeyboard, Apache-2.0) into hkeyboard's JSON.

Reads a checkout's app/src/main/res: the 5-row layouts (xml/kbd_full.xml, xml/kbd_full_fn.xml) and the per-language
key labels (values*/donottranslate-keymap.xml, values*/donottranslate-altchars.xml). Writes one JSON per language:
    {"name", "locale", "layouts": {"full": [row, ...], "fn": [...]}}
row: {"extension": bool, "keys": [key, ...]}
key: {"width": fraction of the keyboard's width, "label", "shift", "popup", "code", "repeat", "sticky", "icon"}
"code" names a special key (shift, ctrl, tab, f5, ...); a key without one types its label.

usage: hk2json.py <hackerskeyboard>/app/src/main/res <output dir> [lang:values-dir ...]
       default languages: en:values it:values-it
"""
import json
import re
import sys
import xml.etree.ElementTree as ET
from pathlib import Path

A = '{http://schemas.android.com/apk/res-auto}'
DEFAULT_WIDTH = 1 / 14
NOTICE = ("Generated by tools/hk2json.py from Hacker's Keyboard (https://github.com/klausw/hackerskeyboard), "
          "Copyright The Android Open Source Project and Klaus Weidner, Apache License 2.0.")

# keycodes.xml's names to hkeyboard's codes
CODES = {
    'key_tab': 'tab', 'key_return': 'return', 'key_space': 'space', 'key_shift': 'shift', 'key_delete': 'backspace',
    'key_settings': 'settings', 'key_f1': 'menu', 'key_dpad_up': 'up', 'key_dpad_down': 'down',
    'key_dpad_left': 'left', 'key_dpad_right': 'right', 'key_dpad_center': 'select', 'key_alt_left': 'alt',
    'key_page_up': 'page_up', 'key_page_down': 'page_down', 'key_escape': 'escape', 'key_forward_del': 'delete',
    'key_ctrl_left': 'ctrl', 'key_caps_lock': 'caps_lock', 'key_scroll_lock': 'scroll_lock', 'key_meta_left': 'meta',
    'key_fn': 'fn', 'key_sysrq': 'sysrq', 'key_break': 'break', 'key_home': 'home', 'key_end': 'end',
    'key_insert': 'insert', 'key_num_lock': 'num_lock',
    **{f'key_fkey_f{i}': f'f{i}' for i in range(1, 13)},
}


def android_string(text):
    """An Android string resource's text with its backslash escapes undone."""
    text = text or ''
    text = re.sub(r'\\u([0-9a-fA-F]{4})', lambda m: chr(int(m.group(1), 16)), text)
    return re.sub(r'\\(.)', lambda m: {'n': '\n', 't': '\t'}.get(m.group(1), m.group(1)), text)


def read_strings(*files):
    strings = {}
    for f in files:
        if f.exists():
            for s in ET.parse(f).getroot().iter('string'):
                strings[s.get('name')] = android_string(s.text)
    return strings


def unique(chars, *exclude):
    seen, out = set(exclude), []
    for c in chars:
        if c not in seen and not c.isspace():
            seen.add(c)
            out.append(c)
    return out


def convert_layout(path, strings):
    def value(v):
        if v is None:
            return None
        if v.startswith('@string/'):
            return strings.get(v[8:], '')
        return android_string(v)

    rows = []
    for row in ET.parse(path).getroot().iter('Row'):
        keys = []
        for k in row.iter('Key'):
            width = k.get(A + 'keyWidth')
            key = {'width': float(width.rstrip('%p')) / 100 if width else DEFAULT_WIDTH}
            code = k.get(A + 'codes')
            if code:
                key['code'] = CODES[code.removeprefix('@integer/')]
            label, shift = value(k.get(A + 'keyLabel')), value(k.get(A + 'shiftLabel'))
            if label:
                key['label'] = label
            if shift and shift != label:
                key['shift'] = shift
            if label and not code:
                letter = label.lower()
                alternates = strings.get(f'alternates_for_{letter}', '') if letter.isalpha() else ''
                popup = unique(value(k.get(A + 'popupCharacters')) or '', label, shift or '')
                popup += unique(alternates, label, shift or '', *popup)
                if popup:
                    key['popup'] = popup
            if k.get(A + 'isRepeatable') == 'true':
                key['repeat'] = True
            if k.get(A + 'isSticky') == 'true':
                key['sticky'] = True
            keys.append(key)
        rows.append({'extension': row.get(A + 'extension') == 'true', 'keys': keys})
    return rows


def main():
    res, out = Path(sys.argv[1]), Path(sys.argv[2])
    langs = [a.split(':', 1) for a in sys.argv[3:]] or [['en', 'values'], ['it', 'values-it']]
    out.mkdir(parents=True, exist_ok=True)
    base = [res / 'values' / 'donottranslate-keymap.xml', res / 'values' / 'donottranslate-altchars.xml']
    for lang, values in langs:
        strings = read_strings(*base, res / values / 'donottranslate-keymap.xml',
                               res / values / 'donottranslate-altchars.xml')
        data = {
            'notice': NOTICE,
            'locale': lang,
            'layouts': {name: convert_layout(res / 'xml' / f'kbd_{name}.xml', strings)
                        for name in ('full', 'full_fn')},
        }
        (out / f'{lang}.json').write_text(json.dumps(data, ensure_ascii=False, indent=1) + '\n')
        print(f'{lang}: {out / f"{lang}.json"}')


if __name__ == '__main__':
    main()
