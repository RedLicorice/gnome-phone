#!/usr/bin/python3 -I
"""gen_looks.py PALETTE.json [--check]: the four looks (marble, sea, forest, plum) of tools/theme/palette.json
("looks") as code for the phone's apps. palette.json (Minerva repo) stays canonical; the outputs are generated and
committed:

  libneo/neo-looks.h                      the C table neo-style.c reads (roles + extras per look)
  apps/settings/src/looks/ns-look-<id>.css  the @define-color ns_* tokens of Neo Settings, one sheet per look

With --check nothing is written: exit status 1 when a committed output differs from what the palette would give
(the drift test; run it after editing palette.json). Change the mapping here, not in the outputs."""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
ORDER = ["marble", "sea", "forest", "plum"]
# the roles in the order of libneo's NeoColor enum (neo-style.h)
ROLES = ["primary", "on_primary", "primary_container", "on_primary_container", "inverse_primary", "secondary",
         "on_secondary", "secondary_container", "on_secondary_container", "tertiary", "on_tertiary",
         "tertiary_container", "on_tertiary_container", "error", "error_container", "surface",
         "surface_container_lowest", "surface_container_low", "surface_container", "surface_container_high",
         "surface_container_highest", "surface_bright", "on_surface", "on_surface_variant", "outline",
         "outline_variant", "inverse_surface", "white"]
# colours of the extras, as 0xRRGGBB
EXTRAS = ["ink", "gold", "gold_hi", "accent", "silver", "silver_dim", "wall_a", "wall_b", "wall_vein", "card", "line",
          "hover", "scrim", "chisel_lit", "chisel_dark"]
# the focus glow is the look's accent; the v3 granite plum look keeps the amber eye (palette.json colors.amber)
AMBER_GLOW = {"plum"}


def rgb(h):
    return tuple(int(h[i:i + 2], 16) for i in (1, 3, 5))


def rgba(h, a):
    r, g, b = rgb(h)
    return "rgba(%d, %d, %d, %s)" % (r, g, b, ("%.2f" % a).rstrip("0").rstrip("."))


def derived(look, p):
    """The values the mockup (chisel.html .day / .night) gives per scheme, not stored as extras: the card's
    translucent colour, the inset rim highlight and the shadow under a card, as CSS colours."""
    ex = look["extras"]
    day = look["scheme"] == "day"
    return {
        "card_a": rgba(ex["card"], ex["card_alpha"]),
        "rim": rgba("#ffffff", 0.9 if day else 0.06),
        "cardsh": rgba(ex["line"] if day else "#000000", 0.16 if day else 0.5),
    }


def glow(lid, look, p):
    return p["colors"]["amber"] if lid in AMBER_GLOW else look["extras"]["accent"]


def c_header(p):
    out = ["/* GENERATED by tools/theme/gen_looks.py from tools/theme/palette.json (\"looks\"): change the palette, not this",
           " * file. Included by neo-style.c after the NeoColor enum. */", "",
           "typedef struct {",
           "  const char *id;            /* marble, sea, forest, plum */",
           "  gboolean    day;           /* a light scheme */",
           "  guint32     role[NEO_N_COLORS];",
           "  guint32     ink, gold, gold_hi, accent, silver, silver_dim, wall_a, wall_b, wall_vein, card, line, hover, scrim,",
           "              chisel_lit, chisel_dark, glow, lapis;",
           "  const char *card_a, *rim, *cardsh;   /* CSS colours: card at its alpha, inset rim, shadow under a card */",
           "} NeoLook;", "", "static const NeoLook neo_looks[] = {"]
    for lid in ORDER:
        look = p["looks"][lid]
        d = derived(look, p)
        out.append("  { \"%s\", %s," % (lid, "TRUE" if look["scheme"] == "day" else "FALSE"))
        out.append("    { /* roles */")
        for r in ROLES:
            out.append("      [NEO_%s] = 0x%s," % (r.upper(), look["roles"][r][1:]))
        out.append("    },")
        for k in EXTRAS:
            out.append("    0x%s, /* %s */" % (look["extras"][k][1:], k))
        out.append("    0x%s, /* glow */" % glow(lid, look, p)[1:])
        out.append("    0x%s, /* lapis */" % p["colors"]["lapis"][1:])
        out.append("    \"%s\", \"%s\", \"%s\" }," % (d["card_a"], d["rim"], d["cardsh"]))
    out.append("};")
    return "\n".join(out) + "\n"


def ns_css(lid, p):
    look = p["looks"][lid]
    ex, ro, col = look["extras"], look["roles"], p["colors"]
    d = derived(look, p)
    day = look["scheme"] == "day"
    if lid == "plum":                      # v3: granite stone dialogs
        dialog, dialog_hi = col["granite"], col["granite_hi"]
    elif day:
        dialog, dialog_hi = ro["surface_bright"], ro["surface_container_high"]
    else:
        dialog, dialog_hi = ro["surface_container_highest"], ro["surface_bright"]
    tokens = [
        ("bg", ro["surface"]), ("wall_a", ex["wall_a"]), ("wall_b", ex["wall_b"]), ("wall_vein", ex["wall_vein"]),
        ("card", ex["card"]), ("card_a", d["card_a"]), ("rim", d["rim"]), ("cardsh", d["cardsh"]),
        ("line", ex["line"]), ("gold", ex["gold"]), ("gold_hi", ex["gold_hi"]), ("parchment", ex["ink"]),
        ("accent", ex["accent"]), ("silver", ex["silver"]), ("silver_dim", ex["silver_dim"]),
        ("lapis", col["lapis"]), ("amber", glow(lid, look, p)), ("platinum", ex["silver"]), ("granite", dialog),
        ("granite_hi", dialog_hi), ("error", ro["error"]), ("on_accent", ro["on_secondary"]),
        ("on_gold", ro["on_primary"]), ("tertiary", ro["tertiary"]), ("chip_bg", ro["surface_container_high"]),
        ("scrim", ex["scrim"]),
    ]
    out = ["/* GENERATED by tools/theme/gen_looks.py from tools/theme/palette.json (looks.%s): the Renaissance tokens of" % lid,
           " * Neo Settings for \"%s\". style.css names them; ns-look.c loads this sheet while the look is in force. */"
           % look["title"]]
    out += ["@define-color ns_%s %s;" % (k, v) for k, v in tokens]
    return "\n".join(out) + "\n"


def outputs(p):
    res = {os.path.join(ROOT, "libneo", "neo-looks.h"): c_header(p)}
    for lid in ORDER:
        res[os.path.join(ROOT, "apps", "settings", "src", "looks", "ns-look-%s.css" % lid)] = ns_css(lid, p)
    return res


def main():
    args = [a for a in sys.argv[1:] if not a.startswith("--")]
    check = "--check" in sys.argv
    if len(args) != 1:
        sys.exit(__doc__)
    p = json.load(open(args[0]))
    bad = 0
    for path, text in outputs(p).items():
        if check:
            have = open(path).read() if os.path.exists(path) else None
            if have != text:
                print("drift:", os.path.relpath(path, ROOT))
                bad = 1
        else:
            os.makedirs(os.path.dirname(path), exist_ok=True)
            open(path, "w").write(text)
            print("wrote", os.path.relpath(path, ROOT))
    sys.exit(bad)


main()
