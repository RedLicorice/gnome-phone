#!/usr/bin/python3 -I
"""gen_app_overrides.py OUT.css APPDIR...: the Renaissance look for the apps that carry their own hex palette
(Messaging, Dialer, Contacts, Calendar ...). For every CSS rule of the given apps with a hex colour in it, emit the
same selector with the colour moved into the theme: teal becomes lapis (dark) or gold (light), dark neutrals take
the night's violet cast, white becomes parchment. Loaded by libneo above the apps' own sheets (priority USER).

Generated: change the mapping here, not in the output."""
import colorsys
import glob
import os
import re
import sys

HEX = re.compile(r"#([0-9a-fA-F]{6})\b")
SKIP = ("-light.css", "-black.css")


def to_hls(h):
    r, g, b = (int(h[i:i + 2], 16) / 255 for i in (0, 2, 4))
    return colorsys.rgb_to_hls(r, g, b)


def from_hls(h, l, s):
    r, g, b = colorsys.hls_to_rgb(h % 1, max(0, min(1, l)), max(0, min(1, s)))
    return "#%02x%02x%02x" % (round(r * 255), round(g * 255), round(b * 255))


def remap(h):
    hue, l, s = to_hls(h)
    deg = hue * 360
    if s < 0.14:                                  # neutrals
        if l > 0.93:
            return "#f0e6d0"                      # white text -> parchment
        if l > 0.75:
            return from_hls(41 / 360, l * 0.97, 0.22)    # light greys -> warm parchment greys
        if l < 0.45:
            return from_hls(250 / 360, l * 0.55, 0.28)   # dark greys -> the night
        return from_hls(41 / 360, l * 0.9, 0.10)
    if 140 <= deg <= 230:                         # teal and cyan family
        if l < 0.42:
            return from_hls(224 / 360, l * 0.85, 0.52)   # dark teal -> lapis
        return from_hls(41 / 360, min(l, 0.78), 0.55)    # light teal -> gold
    return h if False else "#" + h                # other hues (red, orange, calendar colours) stay


def convert(value):
    return HEX.sub(lambda m: remap(m.group(1)), value)


RULE = re.compile(r"([^{}@]+)\{([^{}]*)\}", re.S)


def main():
    out, dirs = sys.argv[1], sys.argv[2:]
    lines = ["/* GENERATED by tools/theme/gen_app_overrides.py: the Renaissance look for the apps' own palettes. */"]
    for d in dirs:
        for path in sorted(glob.glob(os.path.join(d, "src", "*.css"))):
            if path.endswith(SKIP):
                continue
            text = re.sub(r"/\*.*?\*/", "", open(path).read(), flags=re.S)
            lines.append(f"/* {os.path.relpath(path, os.path.dirname(d))} */")
            for sel, body in RULE.findall(text):
                decls = [x.strip() for x in body.split(";") if x.strip()]
                keep = [x + ";" for x in decls if HEX.search(x)]
                if not keep:
                    continue
                new = [convert(x) for x in keep]
                if new == keep:
                    continue
                lines.append(" ".join(sel.split()) + " { " + " ".join(new) + " }")
    open(out, "w").write("\n".join(lines) + "\n")
    print(out, len(lines), "lines")


main()
